// Writes docs/LICENSES.md: every runtime dependency with its version and licence. Run: npm run licenses
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = process.cwd();
const rootPkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));

const seen = new Map();
function visit(name, from) {
  // Resolve like Node does: nested node_modules first, then the project's.
  const candidates = [
    join(from, 'node_modules', name, 'package.json'),
    join(root, 'node_modules', name, 'package.json'),
  ];
  const file = candidates.find((c) => existsSync(c));
  if (!file || seen.has(`${name}@${file}`)) return;
  const pkg = JSON.parse(readFileSync(file, 'utf8'));
  seen.set(`${name}@${file}`, { name: pkg.name, version: pkg.version, license: normalise(pkg) });
  const dir = file.slice(0, -'/package.json'.length);
  for (const dep of Object.keys({ ...pkg.dependencies, ...pkg.optionalDependencies }))
    visit(dep, dir);
}

function normalise(pkg) {
  const l = pkg.license ?? pkg.licenses;
  if (typeof l === 'string') return l;
  if (l && typeof l === 'object')
    return Array.isArray(l) ? l.map((x) => x.type ?? x).join(' OR ') : (l.type ?? 'UNKNOWN');
  return 'UNKNOWN';
}

for (const dep of Object.keys(rootPkg.dependencies)) visit(dep, root);
const rows = [...new Set([...seen.values()].map((r) => JSON.stringify(r)))].map((r) =>
  JSON.parse(r),
);
rows.sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

const isGpl = (l) =>
  /GPL/i.test(l) &&
  !/LGPL/i.test(l) &&
  !/\bOR\b.*(MIT|BSD|Apache|ISC)|(MIT|BSD|Apache|ISC).*\bOR\b/i.test(l);
const flagged = rows.filter((r) => isGpl(r.license) || r.license === 'UNKNOWN');

const notes = {
  'ffmpeg-static':
    'GPL-3.0-or-later. Distributed as a separate executable that Convert starts with an argument list; it is not linked into Convert. Source for the ffmpeg build is available from the ffmpeg-static and ffmpeg projects.',
  '7zip-bin':
    'Wrapper is MIT; 7-Zip itself is LGPL with the unRAR restriction. Started as a separate program.',
  'exiftool-vendored': 'ExifTool is Artistic-1.0 or GPL, started as a separate program.',
  jszip: 'Dual licensed MIT or GPL-3.0-or-later. Convert uses it under MIT.',
  sharp: 'Apache-2.0. libvips is LGPL-3.0 and is loaded as a shared library, not modified.',
  '@vladmandic/face-api':
    'MIT. Ships the TinyFaceDetector weights used for offline face detection.',
  buffers:
    'The package.json has no license field. Pulled in by exceljs (through unzipper). Its upstream repository states MIT/X11; verify before redistributing.',
  '@tesseract.js-data/eng': 'MIT. English language data for offline text detection.',
};

const out = [
  '# Third-party licenses',
  '',
  'Generated by `npm run licenses`. Convert has no network code; these libraries run on your computer only.',
  '',
  '## Notes on specific components',
  '',
  ...Object.entries(notes).map(([k, v]) => `- **${k}**: ${v}`),
  '',
  `## Needs a decision (GPL or unknown, ${flagged.length})`,
  '',
  flagged.length === 0
    ? 'None.'
    : flagged
        .map(
          (r) =>
            `- ${r.name}@${r.version}: ${r.license}${notes[r.name] ? ` (see notes above)` : ''}`,
        )
        .join('\n'),
  '',
  `## All runtime dependencies (${rows.length})`,
  '',
  '| Package | Version | License |',
  '|---|---|---|',
  ...rows.map((r) => `| ${r.name} | ${r.version} | ${r.license.replace(/\|/g, '/')} |`),
  '',
].join('\n');

writeFileSync(join(root, 'docs', 'LICENSES.md'), out);
console.log(`wrote docs/LICENSES.md (${rows.length} packages, ${flagged.length} flagged)`);
